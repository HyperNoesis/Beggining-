// Rebuilds js/providers/scene-library.js from every assets/scenes/*/scene.json (built-ins first, in their original order, then imported scenes by name).
// Usage: node tools/scenes/rebuild_library.js   (run after tools/scenes/make_scenes.py or import_scene.js)
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '../..');
const ctx = {}; ctx.globalThis = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'js/providers/scene-meta.js'), 'utf8'), ctx);
const dir = path.join(root, 'assets/scenes');
const orderFile = path.join(root, 'assets/scenes/_builtin_order.json');
let order = [];
try { order = JSON.parse(fs.readFileSync(orderFile, 'utf8')); } catch (e) {
  // first run: take the order from the current generated library
  try { const c2 = {}; c2.globalThis = c2; vm.createContext(c2); vm.runInContext(fs.readFileSync(path.join(root, 'js/providers/scene-library.js'), 'utf8'), c2); order = c2.VS.SCENE_LIBRARY.filter((m) => !m.imported).map((m) => m.id); fs.writeFileSync(orderFile, JSON.stringify(order)); } catch (_) {}
}
const metas = fs.readdirSync(dir).filter((d) => fs.existsSync(path.join(dir, d, 'scene.json'))).map((d) => JSON.parse(fs.readFileSync(path.join(dir, d, 'scene.json'), 'utf8')));
let prem = []; try { prem = JSON.parse(fs.readFileSync(path.join(root, 'assets/scenes/_premium_order.json'), 'utf8')); } catch (e) {}
// premium (photoreal) scenes first in their chosen order, then the procedural 'classic' built-ins, then any other imports
const rank = (m) => { const p = prem.indexOf(m.id); if (p >= 0) return p; const i = order.indexOf(m.id); return i < 0 ? 1e6 : 1000 + i; };
metas.sort((a, b) => rank(a) - rank(b) || a.name.localeCompare(b.name));
const bad = [];
const good = metas.filter((m) => { const v = ctx.VS.SceneMeta.validate(m); if (!v.ok) bad.push(m.id + ': ' + v.errors.join('; ')); return v.ok; });
fs.writeFileSync(path.join(root, 'js/providers/scene-library.js'),
  '/* GENERATED by tools/scenes/rebuild_library.js — do not edit. Same content as assets/scenes/<id>/scene.json. */\n(function(){ globalThis.VS = globalThis.VS || {}; globalThis.VS.SCENE_LIBRARY = ' + JSON.stringify(good) + '; })();\n');
console.log(good.length + ' scenes written' + (bad.length ? '; SKIPPED invalid: ' + bad.join(' | ') : ''));
